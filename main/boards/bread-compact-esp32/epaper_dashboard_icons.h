/*
 * The remaining descriptors use compact, hand-authored I1 glyph maps. They are
 * intentionally simple: on a 1-bit 800x480 panel, strong silhouettes survive
 * repeated partial refreshes better than anti-aliased pictograms.
 */
#define EP_I1_DESC(name, W, H, STRIDE, ...) \
static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t name##_map[] = { \
    0xff,0xff,0xff,0x00, 0x00,0x00,0x00,0xff, __VA_ARGS__ \
}; \
static const lv_image_dsc_t name = { \
    .header.magic = LV_IMAGE_HEADER_MAGIC, .header.cf = LV_COLOR_FORMAT_I1, \
    .header.flags = 0, .header.w = W, .header.h = H, .header.stride = STRIDE, \
    .data_size = sizeof(name##_map), .data = name##_map \
}

